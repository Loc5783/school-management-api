const express = require('express');
const auth = require('../middlewares/auth');
const roleCheck = require('../middlewares/roleCheck');
const controller = require('../controllers/guardController');
const devices = require('../controllers/guardDeviceController');

const router = express.Router();
router.use(auth, roleCheck(['guard', 'admin', 'principal']));
router.get('/dashboard', controller.getDashboard);
router.get('/students', controller.searchStudents);
router.get('/gate-events', controller.listGateEvents);
router.post('/gate-events', controller.recordGateEvent);
router.get('/visitors', controller.listVisitors);
router.post('/visitors', controller.createVisitor);
router.patch('/visitors/:id/check-out', controller.checkoutVisitor);
router.get('/incidents', controller.listIncidents);
router.post('/incidents', controller.createIncident);
router.patch('/incidents/:id', controller.updateIncident);
router.patch('/incidents/:id/acknowledge', controller.acknowledgeIncident);
router.get('/handovers', controller.listHandovers);
router.get('/receivers', controller.listReceivers);
router.post('/handovers', controller.createHandover);
router.patch('/handovers/:id/accept', controller.acceptHandover);
router.post('/qr/resolve', controller.resolveQrCode);
router.post('/pickup-otp', controller.requestPickupOtp);
router.post('/pickup-otp/:id/verify', controller.verifyPickupOtp);
router.get('/deliveries', controller.listSupplierDeliveries);
router.get('/deliveries/expected-orders', controller.listExpectedDeliveries);
router.post('/deliveries', controller.createSupplierDelivery);
router.patch('/deliveries/:id/check-out', controller.checkoutSupplierDelivery);
router.get('/emergency-mode', controller.getEmergencyMode);
router.post('/emergency-mode', controller.activateEmergencyMode);
router.patch('/emergency-mode/:id/resolve', controller.resolveEmergencyMode);
router.get('/reports', controller.getGuardReport);
router.get('/devices', devices.listDevices);
router.post('/devices', roleCheck(['admin', 'principal']), devices.createDevice);
router.patch('/devices/:id', roleCheck(['admin', 'principal']), devices.updateDevice);
router.post('/devices/:id/rotate-token', roleCheck(['admin', 'principal']), devices.rotateDeviceToken);
router.get('/device-events', devices.listEvents);
router.patch('/device-events/:id/review', devices.reviewEvent);

module.exports = router;
